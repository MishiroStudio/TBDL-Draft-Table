function loadState() {
  try {
    const saved = JSON.parse(localStorage.getItem(STORAGE_KEY));
    if (!saved) return;

    state.playerCount = Math.min(
      MAX_PLAYERS,
      Math.max(MIN_PLAYERS, Number(saved.playerCount) || 4)
    );

    if (Array.isArray(saved.trainerNames)) {
      for (let i = 0; i < MAX_PLAYERS; i++) {
        if (typeof saved.trainerNames[i] === "string") {
          state.trainerNames[i] = saved.trainerNames[i];
        }
      }
    }

    if (saved.drafted && typeof saved.drafted === "object") {
      const validNames = new Set(POKEMON.map(p => p.name));
      for (const [name, owner] of Object.entries(saved.drafted)) {
        if (validNames.has(name)) state.drafted[name] = owner;
      }
    }
  } catch (_) {}
}

