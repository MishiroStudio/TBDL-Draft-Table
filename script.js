function spriteCandidates(name) {
  const slug = slugify(name);
  const candidates = [];

  for (const alias of SPRITE_ALIASES[name] || []) {
    candidates.push(`sprites/${alias}.png`);
    candidates.push(`sprites/${alias}.webp`);
  }

  candidates.push(`sprites/${slug}.png`, `sprites/${slug}.webp`);

  if (slug.startsWith("mega-")) {
    const rest = slug.slice(5);
    candidates.push(`sprites/${rest}-mega.png`);
    candidates.push(`sprites/${rest}-mega.webp`);

    const match = rest.match(/^(.*)-(x|y|z)$/);
    if (match) {
      candidates.push(`sprites/${match[1]}-mega-${match[2]}.png`);
      candidates.push(`sprites/${match[1]}-mega${match[2]}.png`);
      candidates.push(`sprites/${match[1]}meg${match[2]}.png`);
    }
  }

  if (slug.startsWith("alolan-")) {
    const rest = slug.slice(7);
    candidates.push(`sprites/${rest}-alola.png`);
    candidates.push(`sprites/${rest}-alolan.png`);
  }

  if (slug.startsWith("galarian-")) {
    const rest = slug.slice(9);
    candidates.push(`sprites/${rest}-galar.png`);
    candidates.push(`sprites/${rest}-galarian.png`);
  }

  if (slug.startsWith("hisuian-")) {
    const rest = slug.slice(8);
    candidates.push(`sprites/${rest}-hisui.png`);
    candidates.push(`sprites/${rest}-hisuian.png`);
  }

  if (slug.startsWith("paldean-")) {
    const rest = slug.slice(8);
    candidates.push(`sprites/${rest}-paldea.png`);
    candidates.push(`sprites/${rest}-paldean.png`);
  }

  candidates.push(`sprites/${slug.replace("-male", "-m")}.png`);
  candidates.push(`sprites/${slug.replace("-female", "-f")}.png`);

  const compact = slug.replace(/-/g, "");
  candidates.push(`sprites/${compact}.png`);
  candidates.push(`sprites/${compact}.webp`);

  return [...new Set(candidates)];
}

function createSprite(name) {
  const box = document.createElement("div");
  box.className = "sprite-box";

  const img = document.createElement("img");
  img.alt = name;
  img.draggable = false;

  const candidates = spriteCandidates(name);
  let index = 0;

  const tryNext = () => {
    if (index >= candidates.length) {
      img.remove();
      const fallback = document.createElement("div");
      fallback.className = "sprite-fallback";
      fallback.textContent = "Sprite fehlt";
      box.appendChild(fallback);
      return;
    }
    img.src = candidates[index++];
  };

  img.addEventListener("error", tryNext);
  box.appendChild(img);
  tryNext();
  return box;
}

