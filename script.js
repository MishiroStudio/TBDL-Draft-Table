const MAX_BUDGET = 100;
const MIN_PLAYERS = 4;
const MAX_PLAYERS = 8;
const STORAGE_KEY = "pokemon-draft-board-v2-current-csv";

let state = {
  playerCount: 4,
  trainerNames: Array.from({ length: MAX_PLAYERS }, (_, i) => `Trainer ${i + 1}`),
  drafted: {}
};

let draggedPokemon = null;

const board = document.getElementById("board");
const teams = document.getElementById("teams");
const playerCount = document.getElementById("playerCount");
const resetBtn = document.getElementById("resetBtn");
const searchInput = document.getElementById("searchInput");
const availableCount = document.getElementById("availableCount");
const toast = document.getElementById("toast");

function loadState() {
  try {
    const saved = JSON.parse(localStorage.getItem(STORAGE_KEY));
    if (!saved) return;

    state.playerCount = Math.min(
      MAX_PLAYERS,
      Math.max(MIN_PLAYERS, Number(saved.playerCount) || 4)
    );

    if (Array.isArray(saved.trainerNames)) {
      for (let i = 0; i < MAX_PLAYERS; i++) {
        if (typeof saved.trainerNames[i] === "string") {
          state.trainerNames[i] = saved.trainerNames[i];
        }
      }
    }

    if (saved.drafted && typeof saved.drafted === "object") {
      // Ignore saved Pokémon that are no longer present in the current CSV.
      const validNames = new Set(POKEMON.map(p => p.name));
      for (const [name, owner] of Object.entries(saved.drafted)) {
        if (validNames.has(name)) state.drafted[name] = owner;
      }
    }
  } catch (_) {}
}

function saveState() {
  localStorage.setItem(STORAGE_KEY, JSON.stringify(state));
}

function slugify(name) {
  return name
    .toLowerCase()
    .normalize("NFD").replace(/[\u0300-\u036f]/g, "")
    .replace(/♀/g, "-female")
    .replace(/♂/g, "-male")
    .replace(/['’\.]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

